def stem(w):
    for e in ENDINGS:
        if w.endswith(e) and len(w)-len(e) >= 3:
            w = w[:-len(e)]; break
    return w[:-1] if len(w) > 4 and w[-1] in "еийь" else w
    return w
    return w
